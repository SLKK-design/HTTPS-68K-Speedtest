#!/usr/bin/env python3
"""Writes src/vectors.h: the inputs the crypto tests time.

- A P-256 key and an ECDSA signature over a SHA-256 hash (the size of the
  signatures in a Notion handshake), made with the openssl command line.
- The same for P-384 with SHA-384 (the GTS Root R4 check).
- The RFC 7748 section 5.2 X25519 vector, checked here with a small
  pure-Python ladder so a typo can't slip into the header.

Every method on the Mac must reproduce these answers, so a fast but wrong
method shows up as WRONG instead of as a good time.

Usage: python3 tools/gen_vectors.py [out.h]   (default src/vectors.h)
"""
import hashlib
import os
import subprocess
import sys
import tempfile

MESSAGE = b"Notion Classic speed test, Oct 2026"


def run(*args, data=None):
    return subprocess.run(args, input=data, check=True, capture_output=True).stdout


def der_ints(der):
    """r, s from a DER ECDSA-Sig-Value (SEQUENCE of two INTEGERs)."""
    assert der[0] == 0x30
    i = 2 if der[1] < 0x80 else 2 + (der[1] & 0x7F)
    out = []
    for _ in range(2):
        assert der[i] == 0x02
        n = der[i + 1]
        out.append(int.from_bytes(der[i + 2:i + 2 + n], "big"))
        i += 2 + n
    return out


def ec_vector(curve, nbytes, hashfn):
    with tempfile.TemporaryDirectory() as tmp:
        key = os.path.join(tmp, "key.pem")
        digest = os.path.join(tmp, "digest.bin")
        sig = os.path.join(tmp, "sig.der")
        run("openssl", "ecparam", "-name", curve, "-genkey", "-noout", "-out", key)
        pub_der = run("openssl", "ec", "-in", key, "-pubout", "-outform", "DER")
        point = pub_der[-(2 * nbytes + 1):]
        assert point[0] == 0x04
        h = hashfn(MESSAGE).digest()
        with open(digest, "wb") as f:
            f.write(h)
        run("openssl", "pkeyutl", "-sign", "-inkey", key, "-in", digest, "-out", sig)
        run("openssl", "pkeyutl", "-verify", "-inkey", key, "-in", digest, "-sigfile", sig)
        with open(sig, "rb") as f:
            r, s = der_ints(f.read())
    return point[1:], h, r.to_bytes(nbytes, "big") + s.to_bytes(nbytes, "big")


def x25519(k, u):
    """RFC 7748 X25519, straight from section 5."""
    p = 2**255 - 19
    k = bytearray(k)
    k[0] &= 248
    k[31] &= 127
    k[31] |= 64
    k = int.from_bytes(k, "little")
    x1 = int.from_bytes(u, "little") & ((1 << 255) - 1)
    x2, z2, x3, z3, swap = 1, 0, x1, 1, 0
    for t in reversed(range(255)):
        bit = (k >> t) & 1
        swap ^= bit
        if swap:
            x2, x3, z2, z3 = x3, x2, z3, z2
        swap = bit
        a, b = (x2 + z2) % p, (x2 - z2) % p
        aa, bb = a * a % p, b * b % p
        e = (aa - bb) % p
        c, d = (x3 + z3) % p, (x3 - z3) % p
        da, cb = d * a % p, c * b % p
        x3 = (da + cb) ** 2 % p
        z3 = x1 * (da - cb) ** 2 % p
        x2 = aa * bb % p
        z2 = e * (aa + 121665 * e) % p
    if swap:
        x2, z2 = x3, z3
    return (x2 * pow(z2, p - 2, p) % p).to_bytes(32, "little")


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    return "static const unsigned char %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "src", "vectors.h")

    p256_pub, p256_hash, p256_sig = ec_vector("prime256v1", 32, hashlib.sha256)
    p384_pub, p384_hash, p384_sig = ec_vector("secp384r1", 48, hashlib.sha384)

    x_scalar = bytes.fromhex("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4")
    x_point = bytes.fromhex("e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c")
    x_expect = bytes.fromhex("c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552")
    assert x25519(x_scalar, x_point) == x_expect, "RFC 7748 vector mismatch"

    with open(out, "w") as f:
        f.write("/* vectors.h: generated by tools/gen_vectors.py, do not edit.\n"
                "   Keys are throwaway test keys; nothing here is secret. */\n#pragma once\n\n")
        f.write("/* P-256: public key X|Y, SHA-256 hash, signature r|s (big-endian) */\n")
        f.write(c_array("kP256Pub", p256_pub))
        f.write(c_array("kP256Hash", p256_hash))
        f.write(c_array("kP256Sig", p256_sig))
        f.write("\n/* P-384: public key X|Y, SHA-384 hash, signature r|s (big-endian) */\n")
        f.write(c_array("kP384Pub", p384_pub))
        f.write(c_array("kP384Hash", p384_hash))
        f.write(c_array("kP384Sig", p384_sig))
        f.write("\n/* X25519, RFC 7748 section 5.2 (little-endian) */\n")
        f.write(c_array("kX25519Scalar", x_scalar))
        f.write(c_array("kX25519Point", x_point))
        f.write(c_array("kX25519Expect", x_expect))
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
