#!/usr/bin/env python3
"""OPT #6b: generate the m68k asm + C model for the P-256 Solinas
column-sum reduction (solinas_p256_m68k.s in Claude 68, tests/solinas_model.c here).

Replaces the table-building half of uECC's vli_mmod_fast_secp256r1
(uint32 version): instead of materializing s1/s2/s3/s4/d1..d4 in a tmp
array and running 10 separate 8-word vli_add/vli_sub passes over result
in RAM, compute each output word as one column sum with the running
carry held in registers.

Exactness: integer addition is associative, so the column-wise total
equals the C version's sequential total: V = t + 2*s1 + 2*s2 + s3 + s4
- d1 - d2 - d3 - d4.  The asm emits result = V mod 2^256 and returns
carry = V >> 256 (signed, |carry| < 8), identical to the C 'carry'
accumulator.  The caller keeps uECC's normalization loop.

Column model: 64-bit signed accumulator acc (d1:d0 hi:lo).
  add term:  add.l OFF(%a1),%d0 ; addx.l %d6,%d1     (d6 = 0)
  sub term:  sub.l OFF(%a1),%d0 ; subx.l %d6,%d1
  x2/x3:     load once into d5, repeat add.l %d5,%d0 ; addx.l %d6,%d1
  rotate:    result[i] = d0;  acc >>= 32 arithmetic:
             move.l %d1,%d0 (sets N from value) ; smi.b %d1 ; extb.l %d1
X-flag safety: every ADD/SUB starts its own 2-instruction chain; MOVE,
SMI, EXTB do not modify X.

Run: python3 tools/gen_solinas_m68k.py. The asm goes into the Claude 68
checkout next to this repo (../Claude68), or into $CLAUDE68_DIR.
"""

import os

# (coeff, product_index) per output column, derived from uECC
# curve-specific.inc vli_mmod_fast_secp256r1 (uint32 version):
#   base + 2*s1 + 2*s2 + s3 + s4 - d1 - d2 - d3 - d4
# Cross-checked against the FIPS 186 P-256 reduction formulas.
COLUMNS = [
    [(1, 0), (1, 8), (1, 9), (-1, 11), (-1, 12), (-1, 13), (-1, 14)],
    [(1, 1), (1, 9), (1, 10), (-1, 12), (-1, 13), (-1, 14), (-1, 15)],
    [(1, 2), (1, 10), (1, 11), (-1, 13), (-1, 14), (-1, 15)],
    [(1, 3), (2, 11), (2, 12), (1, 13), (-1, 8), (-1, 9), (-1, 15)],
    [(1, 4), (2, 12), (2, 13), (1, 14), (-1, 9), (-1, 10)],
    [(1, 5), (2, 13), (2, 14), (1, 15), (-1, 10), (-1, 11)],
    [(1, 6), (1, 13), (3, 14), (2, 15), (-1, 8), (-1, 9)],
    [(1, 7), (1, 8), (3, 15), (-1, 10), (-1, 11), (-1, 12), (-1, 13)],
]


def check_table():
    """Re-derive the table from the s/d row definitions and compare."""
    rows = {
        's1': ([0, 0, 0, 11, 12, 13, 14, 15], 2),
        's2': ([0, 0, 0, 12, 13, 14, 15, 0], 2),
        's3': ([8, 9, 10, 0, 0, 0, 14, 15], 1),
        's4': ([9, 10, 11, 13, 14, 15, 13, 8], 1),
        'd1': ([11, 12, 13, 0, 0, 0, 8, 10], -1),
        'd2': ([12, 13, 14, 15, 0, 0, 9, 11], -1),
        'd3': ([13, 14, 15, 8, 9, 10, 0, 12], -1),
        'd4': ([14, 15, 0, 9, 10, 11, 0, 13], -1),
    }
    # rows use index 0 to mean "zero word" — only valid because no s/d
    # row ever references product[0]
    for col in range(8):
        terms = {col: 1}  # base t
        for idxs, coeff in rows.values():
            p = idxs[col]
            if p != 0:
                terms[p] = terms.get(p, 0) + coeff
        expect = {p: c for p, c in terms.items() if c != 0}
        got = {}
        for c, p in COLUMNS[col]:
            got[p] = got.get(p, 0) + c
        assert got == expect, f"col {col}: {got} != {expect}"


def emit_asm(path):
    lines = []
    o = lines.append
    o("| solinas_p256_columns_m68k — P-256 Solinas reduction column sums,")
    o("| m68k 68020+.  GENERATED by tools/gen_solinas_m68k.py in")
    o("| HTTPS-68K-Speedtest — do not hand-edit, rerun the generator.")
    o("|")
    o("| int solinas_p256_columns_m68k(uint32_t *result,")
    o("|                               const uint32_t *product);")
    o("| result[i] = column sum of product words (coeffs -1/+1/+2/+3 from")
    o("| t + 2*s1 + 2*s2 + s3 + s4 - d1..d4), 64-bit signed carry kept in")
    o("| d1:d0 across columns; returns V >> 256 (small signed carry) for")
    o("| the caller's normalization loop.  See generator for the model.")
    o("|")
    o("| d0 acc lo / return | d1 acc hi | d5 repeated-term load | d6 zero")
    o("| a0 result (post-inc) | a1 product")
    o("")
    o("    .text")
    o("    .even")
    o("    .global solinas_p256_columns_m68k")
    o("")
    o("solinas_p256_columns_m68k:")
    o("    movem.l %d5-%d6,-(%sp)")
    o("    movea.l 12(%sp),%a0     | result")
    o("    movea.l 16(%sp),%a1     | product")
    o("    moveq   #0,%d6          | permanent zero")
    o("    moveq   #0,%d0          | acc = 0")
    o("    moveq   #0,%d1")
    o("")
    for col, terms in enumerate(COLUMNS):
        o(f"| column {col}: " + " ".join(
            f"{'+' if c > 0 else '-'}{'' if abs(c) == 1 else abs(c)}p{p}"
            for c, p in terms))
        for c, p in terms:
            off = 4 * p
            if c == 1:
                o(f"    add.l   {off}(%a1),%d0")
                o("    addx.l  %d6,%d1")
            elif c == -1:
                o(f"    sub.l   {off}(%a1),%d0")
                o("    subx.l  %d6,%d1")
            elif c in (2, 3):
                o(f"    move.l  {off}(%a1),%d5")
                for _ in range(c):
                    o("    add.l   %d5,%d0")
                    o("    addx.l  %d6,%d1")
            else:
                raise AssertionError(c)
        o(f"    move.l  %d0,(%a0)+      | result[{col}]")
        if col < 7:
            o("    move.l  %d1,%d0         | acc >>= 32 (arithmetic)")
            o("    smi.b   %d1             | N still from the move")
            o("    extb.l  %d1")
        else:
            o("    move.l  %d1,%d0         | return carry = V >> 256")
        o("")
    o("    movem.l (%sp)+,%d5-%d6")
    o("    rts")
    o("")
    o("| End solinas_p256_columns_m68k")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def emit_model(path):
    lines = []
    o = lines.append
    o("/* GENERATED by tools/gen_solinas_m68k.py — C model of")
    o(" * solinas_p256_columns_m68k, same column order and carry model. */")
    o("#include <stdint.h>")
    o("")
    o("static int32_t solinas_p256_columns_model(uint32_t *result,")
    o("                                          const uint32_t *p) {")
    o("    int64_t acc = 0;")
    for col, terms in enumerate(COLUMNS):
        parts = []
        for c, p in terms:
            if c > 0:
                parts.append(f"+ (int64_t){c} * p[{p}]" if c != 1
                             else f"+ (int64_t)p[{p}]")
            else:
                parts.append(f"- (int64_t)p[{p}]" if c == -1
                             else f"- (int64_t){-c} * p[{p}]")
        o(f"    acc += {' '.join(parts)[2:]};")
        o(f"    result[{col}] = (uint32_t)acc;")
        o("    acc >>= 32;")
    o("    return (int32_t)acc;")
    o("}")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    check_table()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    c68 = os.environ.get("CLAUDE68_DIR", os.path.join(root, "..", "Claude68"))
    emit_asm(os.path.join(c68, "src/core/net/solinas_p256_m68k.s"))
    emit_model(os.path.join(root, "tests/solinas_model.c"))
    print("wrote " + os.path.join(c68, "src/core/net/solinas_p256_m68k.s") + " + tests/solinas_model.c")


if __name__ == "__main__":
    main()
